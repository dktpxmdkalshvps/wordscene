-- WordScene 기본 데이터베이스 스키마 마이그레이션.
-- 포함 테이블: works, book_contents, movie_quotes_ko_en
-- 이 마이그레이션은 20260920120000_device_progress.sql 및 20260921000000_generated_questions.sql 실행 전에 먼저 적용됩니다.

-- 1. works (작품 목록)
create table if not exists public.works (
  id          text primary key,
  title       text not null,
  author      text not null,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);

alter table public.works enable row level security;

-- anon 롤 읽기 정책
create policy "anon read works"
  on public.works for select to anon
  using (true);

-- 2. book_contents (고전 문학 원문 및 한국어 번역)
create table if not exists public.book_contents (
  candidate_id     text primary key,
  work_id          text not null references public.works(id) on delete cascade,
  no_in_work       integer not null default 1,
  segment_heading  text not null default '',
  original_text    text not null,
  translation_ko   text not null,
  difficulty       text not null default 'Beginner',
  learning_focus   text[],
  selection_score  numeric not null default 0,
  segment_id       text,
  source_url       text,
  source_sha256    text,
  quote_sha256     text unique,
  source_start     integer,
  source_end       integer,
  review_status    text not null default 'drafted' check (review_status in ('drafted', 'candidate', 'selected', 'rejected')),
  created_at       timestamptz not null default now()
);

alter table public.book_contents enable row level security;

-- anon 롤 읽기 정책
create policy "anon read book_contents"
  on public.book_contents for select to anon
  using (true);

-- 조회 성능 최적화 인덱스
create index if not exists idx_book_contents_work_review 
  on public.book_contents(work_id, review_status, selection_score desc);

-- 3. movie_quotes_ko_en (영화 명대사 원문 및 영어 번역)
create table if not exists public.movie_quotes_ko_en (
  id             bigint generated by default as identity primary key,
  movie_title    text not null,
  quote_no       text not null,
  original_ko    text not null,
  translation_en text not null,
  notes          text,
  review_status  text not null default 'drafted' check (review_status in ('drafted', 'candidate', 'selected', 'rejected')),
  created_at     timestamptz not null default now()
);

alter table public.movie_quotes_ko_en enable row level security;

-- anon 롤 읽기 정책
create policy "anon read movie_quotes_ko_en"
  on public.movie_quotes_ko_en for select to anon
  using (true);

-- 조회 성능 최적화 인덱스
create index if not exists idx_movie_quotes_title_review 
  on public.movie_quotes_ko_en(movie_title, review_status);

